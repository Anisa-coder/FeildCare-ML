from __future__ import annotations

import hashlib
import json
import shutil
import zipfile
from pathlib import Path


# ============================================================
# FIELDCARE DATASET COMPRESSOR
# ============================================================
#
# Compresses:
#
#   dataset/
#       1/
#       2/
#       ...
#       18/
#       label.txt
#
#   real_world/
#       images/
#       results/
#       label.txt
#
# Archives are automatically split so that each ZIP remains
# below the configured GitHub-safe size.
#
# Original files are NOT deleted.
#
# ============================================================


ROOT = Path(__file__).resolve().parent.parent

DATASET_DIR = ROOT / "dataset"

REAL_WORLD_DIR = ROOT / "real_world"

ARCHIVE_DIR = ROOT / "archives"

DATASET_ARCHIVE_DIR = (
    ARCHIVE_DIR / "dataset-archive"
)

REAL_WORLD_ARCHIVE_DIR = (
    ARCHIVE_DIR / "real_world-archive"
)

MANIFEST_FILE = (
    ARCHIVE_DIR / "manifest.json"
)


# ============================================================
# SETTINGS
# ============================================================

# GitHub has a 100 MB per-file limit.
#
# Keep a comfortable margin.

MAX_ARCHIVE_SIZE = 90 * 1024 * 1024


# ZIP compression level.
#
# 9 = maximum compression.
#
# IMPORTANT:
# JPEG/PNG files are already compressed, so the difference
# between level 6 and 9 may be relatively small.

COMPRESSION_LEVEL = 9


IMAGE_EXTENSIONS = {
    ".jpg",
    ".jpeg",
    ".png",
    ".bmp",
    ".webp",
    ".tif",
    ".tiff",
}


# ============================================================
# HELPERS
# ============================================================

def sha256_file(path: Path) -> str:

    sha = hashlib.sha256()

    with open(
        path,
        "rb"
    ) as file:

        while True:

            chunk = file.read(
                1024 * 1024
            )

            if not chunk:
                break

            sha.update(chunk)

    return sha.hexdigest()


def is_image(path: Path) -> bool:

    return (
        path.is_file()
        and
        path.suffix.lower()
        in IMAGE_EXTENSIONS
    )


def archive_size(path: Path) -> int:

    if not path.exists():
        return 0

    return path.stat().st_size


def format_size(size: int) -> str:

    if size < 1024:

        return f"{size} B"

    if size < 1024 * 1024:

        return f"{size / 1024:.2f} KB"

    if size < 1024 * 1024 * 1024:

        return f"{size / (1024 * 1024):.2f} MB"

    return f"{size / (1024 * 1024 * 1024):.2f} GB"


# ============================================================
# ZIP CREATION
# ============================================================

def create_zip(
    files: list[tuple[Path, str]],
    output: Path,
):

    output.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    if output.exists():

        print(
            f"Removing existing archive: "
            f"{output.name}"
        )

        output.unlink()

    print()
    print(
        f"Creating: {output}"
    )

    with zipfile.ZipFile(
        output,
        "w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=COMPRESSION_LEVEL,
    ) as archive:

        for source, archive_name in files:

            print(
                f"  + {archive_name}"
            )

            archive.write(
                source,
                archive_name
            )

    print(
        f"Created: "
        f"{format_size(output.stat().st_size)}"
    )


# ============================================================
# SPLIT FILES INTO ARCHIVES
# ============================================================

def create_split_archives(
    files: list[tuple[Path, str]],
    output_dir: Path,
    prefix: str,
):

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    # Remove old archives generated by this prefix.

    for old_file in output_dir.glob(
        f"{prefix}_part_*.zip"
    ):

        old_file.unlink()

    part = 1

    current_files = []

    # --------------------------------------------------------
    # We estimate based on source size first.
    #
    # Since images are already compressed, this gives a good
    # approximation while avoiding creating and deleting ZIPs
    # repeatedly.
    # --------------------------------------------------------

    current_size = 0

    for source, archive_name in files:

        source_size = (
            source.stat().st_size
        )

        # If adding this file would make the archive
        # exceed our safe threshold, start another part.

        if (
            current_files
            and
            current_size + source_size
            > MAX_ARCHIVE_SIZE
        ):

            output = (
                output_dir /
                f"{prefix}_part_{part:03d}.zip"
            )

            create_zip(
                current_files,
                output
            )

            part += 1

            current_files = []

            current_size = 0

        current_files.append(
            (
                source,
                archive_name
            )
        )

        current_size += source_size

    # Remaining files.

    if current_files:

        output = (
            output_dir /
            f"{prefix}_part_{part:03d}.zip"
        )

        create_zip(
            current_files,
            output
        )

    return part


# ============================================================
# DATASET
# ============================================================

def collect_dataset_files():

    if not DATASET_DIR.exists():

        raise FileNotFoundError(
            f"Dataset folder not found:\n"
            f"{DATASET_DIR}"
        )

    files = []

    # --------------------------------------------------------
    # Class folders are detected dynamically.
    # --------------------------------------------------------

    class_folders = sorted(
        [
            folder
            for folder in DATASET_DIR.iterdir()
            if (
                folder.is_dir()
                and folder.name.isdigit()
            )
        ],
        key=lambda p: int(p.name)
    )

    print()
    print(
        f"Dataset classes found: "
        f"{len(class_folders)}"
    )

    for folder in class_folders:

        class_id = folder.name

        images = sorted(
            [
                path
                for path in folder.rglob("*")
                if is_image(path)
            ]
        )

        print(
            f"Class {class_id}: "
            f"{len(images):,} images"
        )

        for image in images:

            # Inside archive:
            #
            # dataset/1/image.jpg
            #
            relative = (
                image.relative_to(
                    DATASET_DIR
                )
            )

            archive_name = (
                "dataset/"
                +
                relative.as_posix()
            )

            files.append(
                (
                    image,
                    archive_name
                )
            )

    # --------------------------------------------------------
    # label.txt
    # --------------------------------------------------------

    label_file = (
        DATASET_DIR /
        "label.txt"
    )

    if label_file.exists():

        files.append(
            (
                label_file,
                "dataset/label.txt"
            )
        )

    return files


# ============================================================
# REAL WORLD
# ============================================================

def collect_real_world_files():

    if not REAL_WORLD_DIR.exists():

        print(
            "real_world folder does not exist."
        )

        return []

    files = []

    for path in sorted(
        REAL_WORLD_DIR.rglob("*")
    ):

        if not path.is_file():

            continue

        # Never include previous archives.

        if (
            "archives"
            in path.parts
        ):

            continue

        relative = (
            path.relative_to(
                REAL_WORLD_DIR
            )
        )

        archive_name = (
            "real_world/"
            +
            relative.as_posix()
        )

        files.append(
            (
                path,
                archive_name
            )
        )

    return files


# ============================================================
# MANIFEST
# ============================================================

def generate_manifest(
    archive_files
):

    manifest = {
        "project": "FieldCare",
        "max_archive_size": MAX_ARCHIVE_SIZE,
        "archives": [],
    }

    for archive in archive_files:

        print()
        print(
            f"Hashing archive:"
        )

        print(
            f"  {archive.name}"
        )

        digest = sha256_file(
            archive
        )

        manifest[
            "archives"
        ].append(
            {
                "file": str(
                    archive.relative_to(
                        ROOT
                    )
                ),
                "size": archive.stat().st_size,
                "sha256": digest,
            }
        )

    ARCHIVE_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    with open(
        MANIFEST_FILE,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            manifest,
            file,
            indent=2
        )

    print()
    print(
        f"Manifest created:"
    )

    print(
        MANIFEST_FILE
    )


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 80)

    print(
        "FIELDCARE DATASET COMPRESSOR"
    )

    print("=" * 80)

    print()

    print(
        f"Maximum archive size: "
        f"{format_size(MAX_ARCHIVE_SIZE)}"
    )

    print(
        f"Compression level: "
        f"{COMPRESSION_LEVEL}"
    )

    print()

    confirm = input(
        "Start compression? [y/N]: "
    ).strip().lower()

    if confirm != "y":

        print(
            "Cancelled."
        )

        return

    ARCHIVE_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    all_archives = []

    # ========================================================
    # DATASET
    # ========================================================

    print()
    print("=" * 80)

    print(
        "COMPRESSING DATASET"
    )

    print("=" * 80)

    dataset_files = (
        collect_dataset_files()
    )

    if dataset_files:

        create_split_archives(
            dataset_files,
            DATASET_ARCHIVE_DIR,
            "dataset"
        )

        all_archives.extend(
            DATASET_ARCHIVE_DIR.glob(
                "dataset_part_*.zip"
            )
        )

    # ========================================================
    # REAL WORLD
    # ========================================================

    print()
    print("=" * 80)

    print(
        "COMPRESSING REAL-WORLD DATA"
    )

    print("=" * 80)

    real_world_files = (
        collect_real_world_files()
    )

    if real_world_files:

        print(
            f"Real-world files: "
            f"{len(real_world_files):,}"
        )

        create_split_archives(
            real_world_files,
            REAL_WORLD_ARCHIVE_DIR,
            "real_world"
        )

        all_archives.extend(
            REAL_WORLD_ARCHIVE_DIR.glob(
                "real_world_part_*.zip"
            )
        )

    # ========================================================
    # MANIFEST
    # ========================================================

    all_archives = sorted(
        all_archives
    )

    if all_archives:

        generate_manifest(
            all_archives
        )

    # ========================================================
    # FINAL
    # ========================================================

    print()
    print("=" * 80)

    print(
        "COMPRESSION COMPLETE"
    )

    print("=" * 80)

    print()

    print(
        f"Archives:"
    )

    print(
        f"  {ARCHIVE_DIR}"
    )

    print()

    for archive in all_archives:

        print(
            f"{archive.name:<45}"
            f"{format_size(archive.stat().st_size):>12}"
        )

    print()

    print(
        "Original dataset was NOT deleted."
    )

    print(
        "Original real_world data was NOT deleted."
    )

    print()

    print(
        "After uploading and verifying the archives "
        "on GitHub, you can delete the original "
        "image folders locally if required."
    )


if __name__ == "__main__":

    main()